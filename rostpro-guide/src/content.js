// Turns a persona screen's flat content into a sequence of steps for the
// interactive guide: cover -> pain/quote -> trust -> (intro) -> feature blocks -> objections -> outro.
function buildPersonaSteps(screen) {
  const steps = [
    { type: 'cover', eyebrow: screen.eyebrow, title: screen.title, subtitle: screen.subtitle },
  ]
  if (screen.painLead || screen.quote) {
    steps.push({ type: 'pain', painLead: screen.painLead, quote: screen.quote })
  }
  if (screen.trust) {
    steps.push({ type: 'trust', heading: screen.trust.heading, text: screen.trust.text })
  }
  if (screen.intro) {
    steps.push({ type: 'intro', text: screen.intro })
  }
  screen.blocks.forEach((block) => steps.push({ type: 'feature', ...block }))
  if (screen.objections && screen.objections.length) {
    steps.push({ type: 'objections', items: screen.objections, ctaLabel: screen.ctaLabel })
  }
  steps.push({
    type: 'outro',
    ctaLabel: screen.ctaLabel,
    ctaNote: screen.ctaNote,
  })
  return steps
}

function buildExecutorSteps(screen) {
  return [
    { type: 'cover', eyebrow: screen.eyebrow, title: screen.title, subtitle: screen.subtitle },
    { type: 'feature', heading: screen.subtitle, text: screen.honestText, img: screen.img, caption: screen.caption },
    { type: 'notblock', heading: screen.notHeading, text: screen.notText },
    { type: 'softoutro', text: screen.softAction },
  ]
}

export const personaStepsMap = Object.fromEntries(
  Object.entries(personaScreens).map(([key, screen]) => [key, buildPersonaSteps(screen)]),
)

export const executorSteps = buildExecutorSteps(executorScreen)
